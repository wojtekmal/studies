package węzeł;

public class Węzeł
{
    private int wysokość;
    private int x;
    private int y;
    private boolean jestStartowy;

    public Węzeł(int wysokość, int x, int y, boolean jestStartowy)
    {
        this.wysokość = wysokość;
        this.x = x;
        this.y = y;
        this.jestStartowy = jestStartowy;
    }

    
}
